export const dictionaries = { ru, en };
export type Lang = keyof typeof dictionaries;

export function translate(lang: Lang, key: TKey, params?: Record<string, string | number>): string {
  let s: string = dictionaries[lang][key] ?? dictionaries.ru[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

/** Translation outside React (uses the current store language). */
export function t(key: TKey, params?: Record<string, string | number>): string {
  return translate(useStore.getState().lang, key, params);
}

/** Hook: re-renders when the language changes. */
export function useT() {
  const lang = useStore((s) => s.lang);
  return (key: TKey, params?: Record<string, string | number>) => translate(lang, key, params);
}

export function defaultLang(): Lang {
  try {
    const saved = localStorage.getItem("nee.lang");
    if (saved === "ru" || saved === "en") return saved;
  } catch {
    /* ignore */
  }
  return navigator.language.toLowerCase().startsWith("ru") ? "ru" : "en";
}
